#!/usr/bin/env python3
"""Print the combined guideline page (/print_page/) of a built site to PDF.

Run after `mkdocs build`:

    python scripts/build_pdf.py            # writes site/pdf/proteus-rai-guideline.pdf

The print page is generated by mkdocs-print-site-plugin; headless Chromium
(Playwright) renders it exactly like the website, then prints it to A4.

Browser: CI uses Playwright's bundled Chromium (`playwright install chromium`).
Locally you can reuse an installed Chrome instead: `--channel chrome`.
"""
import argparse
import functools
import http.server
import threading
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent

# Injected last, so it overrides mkdocs-print-site-plugin's own @page rules.
# Chromium supports CSS page-margin boxes, so the footer is styled in CSS.
PRINT_CSS = """
@page {
  size: A4 portrait;
  margin: 18mm 16mm 20mm 16mm;
  @bottom-left  { content: "PROTEUS Responsible AI Guideline \\00B7  @@LABEL@@ \\00B7  CC BY 4.0";
                  font: 7.5pt 'IBM Plex Sans', Arial, sans-serif; color: #555; }
  @bottom-center { content: none; }
  @bottom-right { content: counter(page) " / " counter(pages);
                  font: 7.5pt 'IBM Plex Sans', Arial, sans-serif; color: #555; }
}
/* Cover page without footer. (Keep the same margins on every page: Chromium
   lays out the whole document at the first page's width.) */
@page :first {
  @bottom-left { content: none; } @bottom-right { content: none; }
}
/* Material keeps grid/sidebar margins in print: use the full printable width */
html, body { width: auto !important; }
.md-container, .md-main, .md-main__inner, .md-content, .md-content__inner,
#print-site-page { margin: 0 !important; padding: 0 !important; max-width: none !important; }
.md-typeset__scrollwrap { margin-left: 0 !important; margin-right: 0 !important; overflow: visible !important; }
.md-typeset__table { padding: 0 !important; display: block !important; }
.md-typeset__table table:not([class]) { display: table !important; width: 100%; }
.md-sidebar, .md-header, .md-tabs, .md-footer, .md-top { display: none !important; }
#print-site-cover-page { margin: 0 !important; padding: 0 !important; }
#print-site-cover-page .px-cover { width: 100%; height: 245mm; min-height: 0; padding: 16mm 14mm; box-sizing: border-box; }
/* Drop the empty page the plugin adds for each navigation section title */
#print-site-page section.md-section > h1 { display: none; }
"""


class QuietHandler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--site", default=ROOT / "site", type=Path)
    ap.add_argument("--out", default=None, type=Path,
                    help="default: <site>/pdf/proteus-rai-guideline.pdf")
    ap.add_argument("--label", default="",
                    help="version label for the page footer, e.g. 'Version 0.1'")
    ap.add_argument("--channel", default=None,
                    help="browser channel, e.g. 'chrome' to use installed Chrome")
    args = ap.parse_args()

    site = args.site.resolve()
    if not (site / "print_page" / "index.html").exists():
        raise SystemExit(f"{site}/print_page/index.html not found – run `mkdocs build` first.")
    out = (args.out or site / "pdf" / "proteus-rai-guideline.pdf").resolve()
    out.parent.mkdir(parents=True, exist_ok=True)

    handler = functools.partial(QuietHandler, directory=str(site))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    url = f"http://127.0.0.1:{server.server_address[1]}/print_page/"

    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(channel=args.channel)
            page = browser.new_page(viewport={"width": 673, "height": 980})  # A4 minus margins @ 96 dpi
            # Always print the light colour scheme.
            page.emulate_media(color_scheme="light")
            page.goto(url, wait_until="networkidle")
            page.evaluate("document.fonts.ready")
            page.emulate_media(media="print", color_scheme="light")
            page.add_style_tag(content=PRINT_CSS.replace("@@LABEL@@", args.label or "Draft"))
            page.pdf(
                path=str(out),
                prefer_css_page_size=True,
                print_background=True,
                outline=True,       # PDF bookmarks from headings
                tagged=True,        # accessible (tagged) PDF
            )
            browser.close()
    finally:
        server.shutdown()

    print(f"PDF written: {out} ({out.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
